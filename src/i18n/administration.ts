/** UI errors are fixed translations; never expose raw server/provider content. */
export function administrationErrorKey(error: unknown, fallback = 'common.loadFailed') {
  const code = error && typeof error === 'object' && 'code' in error ? String(error.code) : '';
  return ['42501', '401', '403', 'PGRST301'].includes(code) ? 'common.permissionDenied' : fallback;
}
