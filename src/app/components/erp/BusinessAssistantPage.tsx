import { useEffect, useRef, useState, type FormEvent } from 'react';
import { useTranslation } from 'react-i18next';
import { useAuth } from '../../../contexts/AuthContext';
import { useBusinessAssistantStatus } from '../../../hooks/useBusinessAssistantStatus';
import {
  askBusinessAssistantReply,
  businessAssistantErrorMessage,
  type BusinessAssistantReply,
} from '../../../services/aiGatewayService';
import BusinessAssistantStatus from './BusinessAssistantStatus';

export default function BusinessAssistantPage({
  area = 'Business',
  title,
}: {
  area?: 'Finance' | 'HR' | 'Business';
  title?: string;
}) {
  const { i18n } = useTranslation();
  const ar = (i18n.resolvedLanguage || i18n.language).startsWith('ar');
  const { user } = useAuth();
  const status = useBusinessAssistantStatus();
  const [message, setMessage] = useState('');
  const [answer, setAnswer] = useState<BusinessAssistantReply | null>(null);
  const [error, setError] = useState<unknown>(null);
  const [busy, setBusy] = useState(false);
  const generation = useRef(0);
  useEffect(() => {
    generation.current++;
    setMessage('');
    setAnswer(null);
    setError(null);
    setBusy(false);
    return () => {
      generation.current++;
    };
  }, [user?.id, user?.company_id]);
  async function ask(event: FormEvent) {
    event.preventDefault();
    if (busy || !message.trim()) return;
    const request = ++generation.current;
    setBusy(true);
    setError(null);
    setAnswer(null);
    try {
      const result = await askBusinessAssistantReply(
        area === 'Business' ? message : `[${area}] ${message}`,
      );
      if (request === generation.current) {
        setAnswer(result);
        void status.refresh();
      }
    } catch (err) {
      if (request === generation.current) setError(err);
    } finally {
      if (request === generation.current) setBusy(false);
    }
  }
  return (
    <section
      dir={ar ? 'rtl' : 'ltr'}
      className="mx-auto max-w-3xl space-y-6 text-[var(--app-text)]"
    >
      <h1 className="text-3xl font-bold">
        {title ||
          (ar
            ? area === 'Finance'
              ? 'المساعد المالي'
              : area === 'HR'
                ? 'مساعد الموارد البشرية'
                : 'مساعد الأعمال'
            : `${area} assistant`)}
      </h1>
      <p className="text-slate-500">
        {ar
          ? 'اسأل عن ملخص الفواتير الصادرة المصرّح بها لشركتك. يعرض المساعد تحليلاً واقتراحات للقراءة فقط؛ لا يعدّل السجلات ولا ينفّذ مدفوعات.'
          : 'Ask about authorized summaries of issued company invoices. The assistant provides read-only analysis and suggestions; it does not change records or make payments.'}
      </p>
      {area === 'HR' && (
        <p className="text-sm text-slate-500">
          {ar
            ? 'النطاق الحالي متصل بملخص الفواتير. أسئلة الموارد البشرية تعتمد على المعلومات التي تكتبها، ولا تُرفق سجلات الموظفين بالنموذج.'
            : 'The current data connection covers invoice summaries. HR questions use the information you provide; employee records are not attached to the model.'}
        </p>
      )}
      <BusinessAssistantStatus {...status} />
      <form className="space-y-3" onSubmit={ask}>
        <label htmlFor="assistant-message">{ar ? 'سؤالك' : 'Your question'}</label>
        <textarea
          id="assistant-message"
          className="w-full rounded-xl border bg-transparent p-4"
          rows={5}
          maxLength={3800}
          required
          value={message}
          onChange={(e) => setMessage(e.target.value)}
        />
        <button
          className="rounded-lg bg-blue-600 px-5 py-2 text-white disabled:opacity-50"
          disabled={busy || !message.trim()}
        >
          {busy
            ? ar
              ? 'جارٍ إعداد الإجابة…'
              : 'Generating answer…'
            : ar
              ? 'اسأل المساعد'
              : 'Ask assistant'}
        </button>
      </form>
      {error != null && (
        <p role="alert" className="rounded bg-red-50 p-4 text-red-800">
          {businessAssistantErrorMessage(error, ar ? 'ar' : 'en')}
        </p>
      )}
      {answer && (
        <article className="rounded-xl border p-5" aria-live="polite">
          <p className="mb-3 text-xs opacity-70">
            {ar ? 'إجابة مولّدة بواسطة النموذج' : 'Answer generated by the model'} ·{' '}
            <span dir="ltr">{answer.model}</span> ·{' '}
            {new Date(answer.generatedAt).toLocaleString(ar ? 'ar-SA' : 'en-US')}
          </p>
          <div className="whitespace-pre-wrap">{answer.message}</div>
          <p className="mt-4 border-t pt-3 text-xs opacity-70">
            {ar
              ? 'نطاق البيانات: ملخص الفواتير المصرّح بها للشركة، حتى'
              : 'Data scope: authorized company invoice summaries, up to'}{' '}
            {answer.limits.invoiceLimit}{' '}
            {ar
              ? 'فاتورة. راجع الإجابة قبل اتخاذ قرار.'
              : 'invoices. Review the answer before making a decision.'}
          </p>
        </article>
      )}
    </section>
  );
}
