async function columns(path, name, exclude = []) {
  const text = await read(path);
  const start = text.indexOf(`export interface ${name} {`);
  if (start < 0) throw new Error(`Missing source interface ${name}`);
  const block = text.slice(start).split(/^}/m)[0];
  return [...block.matchAll(/^  ([a-zA-Z_][\w]*)\??:/gm)]
    .map((m) => m[1])
    .filter((key) => !exclude.includes(key));
}
