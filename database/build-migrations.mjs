import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { migrationGroups } from './migration-plan.mjs';

const target = new URL('../supabase/migrations/', import.meta.url);
// Normalize before the multiline wrapper expression: its \s* also matches line
// endings, so stripping CRLF first and normalizing later changes blank lines.
const normalizeNewlines = contents => contents.replace(/\r\n/g, '\n');
await mkdir(target, { recursive: true });
for (const group of migrationGroups) {
  const sources = await Promise.all(group.files.map(async file => {
    const contents = normalizeNewlines(await readFile(new URL(file, import.meta.url), 'utf8'));
    return `-- SOURCE: database/${file}\n${contents.replace(/^\s*(BEGIN|COMMIT);\s*$/gm, '')}`;
  }));
  const content = `-- Generated by node database/build-migrations.mjs. Edit the source files.\nBEGIN;\n${sources.join('\n\n')}\nCOMMIT;\n`;
  const path = new URL(group.name, target);
  if (process.argv.includes('--check')) {
    if (normalizeNewlines(await readFile(path, 'utf8')) !== content) throw new Error(`Stale migration: ${fileURLToPath(path)}`);
  } else {
    await writeFile(path, content);
  }
  console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${group.name}`);
}
